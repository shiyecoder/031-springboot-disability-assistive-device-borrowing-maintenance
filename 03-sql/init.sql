CREATE TABLE sys_dict (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  dict_type VARCHAR(40) NOT NULL,
  dict_code VARCHAR(40) NOT NULL,
  dict_label VARCHAR(60) NOT NULL,
  sort INT DEFAULT 0,
  KEY idx_type (dict_type)
