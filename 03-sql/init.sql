DROP DATABASE IF EXISTS new_031;
CREATE DATABASE new_031 DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE new_031;

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;


CREATE TABLE assistive_device (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
  device_no VARCHAR(50) NOT NULL COMMENT '器具编号（业务唯一）',
  name VARCHAR(80) NOT NULL COMMENT '器具名称',
  category VARCHAR(30) NOT NULL COMMENT '器具类别',
  suit_people VARCHAR(60) NOT NULL COMMENT '适用人群',
  brand VARCHAR(60) DEFAULT NULL COMMENT '品牌',
  spec VARCHAR(80) NOT NULL COMMENT '规格型号',
  load_capacity VARCHAR(40) DEFAULT NULL COMMENT '载重',
  capacity_desc VARCHAR(200) DEFAULT NULL COMMENT '适用说明',
  source VARCHAR(60) DEFAULT NULL COMMENT '来源',
  inbound_date DATE DEFAULT NULL COMMENT '入库日期',
  location VARCHAR(100) DEFAULT NULL COMMENT '存放点',
  status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE' COMMENT '状态：AVAILABLE/RESERVED/LENT/TO_DISINFECT/TO_REPAIR/SCRAPPED',
  current_condition VARCHAR(100) DEFAULT NULL COMMENT '当前状况',
  image_url VARCHAR(200) DEFAULT NULL COMMENT '器具图片（相对路径）',
  maintain_count INT DEFAULT 0 COMMENT '累计维护次数',
  last_maintain_date DATE DEFAULT NULL COMMENT '最近维护日期',
  remark VARCHAR(255) DEFAULT NULL COMMENT '备注',
  create_by VARCHAR(50) DEFAULT NULL COMMENT '创建人',
  create_time DATETIME DEFAULT NULL COMMENT '创建时间',
  update_time DATETIME DEFAULT NULL COMMENT '更新时间',
  deleted TINYINT DEFAULT 0 COMMENT '逻辑删除',
  version INT DEFAULT 1 COMMENT '版本号',
  UNIQUE KEY uk_device_no (device_no),
  KEY idx_category (category),
  KEY idx_status (status),
  KEY idx_location (location)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='残障辅助器具台账';


CREATE TABLE device_inspection (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  inspection_no VARCHAR(50) NOT NULL COMMENT '检测单号',
  device_id BIGINT NOT NULL COMMENT '器具ID',
  device_no VARCHAR(50) NOT NULL COMMENT '器具编号',
  category VARCHAR(30) DEFAULT NULL,
  check_items VARCHAR(200) DEFAULT NULL COMMENT '检查项',
  disinfect_method VARCHAR(120) DEFAULT NULL COMMENT '消毒方式',
  result VARCHAR(20) DEFAULT 'PASS' COMMENT 'PASS/FAIL/PENDING',
  inspector VARCHAR(50) DEFAULT NULL COMMENT '执行人',
  inspect_time DATETIME DEFAULT NULL COMMENT '检测时间',
  next_due_date DATE DEFAULT NULL COMMENT '下次到期日',
  photo_url VARCHAR(200) DEFAULT NULL,
  remark VARCHAR(255) DEFAULT NULL,
  create_time DATETIME DEFAULT NULL,
  UNIQUE KEY uk_inspection_no (inspection_no),
  KEY idx_device (device_id),
  KEY idx_time (inspect_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='检测消毒记录';


CREATE TABLE borrow_application (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  app_no VARCHAR(50) NOT NULL COMMENT '业务编号',
  applicant_name VARCHAR(50) NOT NULL COMMENT '使用人姓名',
  applicant_phone VARCHAR(20) DEFAULT NULL,
  agent_name VARCHAR(50) DEFAULT NULL COMMENT '代办人',
  user_condition VARCHAR(120) DEFAULT NULL COMMENT '身体条件',
  device_category VARCHAR(30) NOT NULL COMMENT '申请类别',
  expect_start DATE DEFAULT NULL,
  expect_end DATE DEFAULT NULL,
  purpose VARCHAR(255) DEFAULT NULL,
  delivery_type VARCHAR(20) DEFAULT 'SELF' COMMENT 'SELF 自提 / DELIVER 配送',
  proof_url VARCHAR(200) DEFAULT NULL COMMENT '需求证明',
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING_ASSESS' COMMENT '状态',
  current_stage VARCHAR(30) DEFAULT NULL COMMENT '当前阶段',
  owner_name VARCHAR(50) DEFAULT NULL COMMENT '责任人',
  assessor_name VARCHAR(50) DEFAULT NULL COMMENT '评估员',
  device_id BIGINT DEFAULT NULL,
  device_no VARCHAR(50) DEFAULT NULL,
  borrow_days INT DEFAULT NULL,
  overdue TINYINT DEFAULT 0 COMMENT '是否逾期',
  reject_reason VARCHAR(255) DEFAULT NULL,
  create_by BIGINT DEFAULT NULL,
  create_by_name VARCHAR(50) DEFAULT NULL,
  create_time DATETIME DEFAULT NULL,
  update_time DATETIME DEFAULT NULL,
  version INT DEFAULT 1,
  UNIQUE KEY uk_app_no (app_no),
  KEY idx_status (status),
  KEY idx_applicant (applicant_name),
  KEY idx_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='借用维护单';


CREATE TABLE adaptation_assessment (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  app_id BIGINT NOT NULL,
  app_no VARCHAR(50) DEFAULT NULL,
  assessor_name VARCHAR(50) DEFAULT NULL,
  suggest_model VARCHAR(120) DEFAULT NULL COMMENT '建议型号',
  suggest_parts VARCHAR(200) DEFAULT NULL COMMENT '建议附件',
  borrow_days INT DEFAULT NULL,
  need_deposit TINYINT DEFAULT 0,
  deposit_amount DECIMAL(10,2) DEFAULT 0.00,
  guidance VARCHAR(500) DEFAULT NULL COMMENT '使用指导',
  conclusion VARCHAR(100) DEFAULT NULL COMMENT '评估结论',
  assess_time DATETIME DEFAULT NULL,
  remark VARCHAR(255) DEFAULT NULL,
  KEY idx_app (app_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='适配评估';


CREATE TABLE device_reservation (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  reserve_no VARCHAR(50) NOT NULL,
  app_id BIGINT NOT NULL,
  app_no VARCHAR(50) DEFAULT NULL,
  device_id BIGINT NOT NULL,
  device_no VARCHAR(50) DEFAULT NULL,
  device_name VARCHAR(80) DEFAULT NULL,
  lock_time DATETIME DEFAULT NULL,
