CREATE TABLE sys_menu (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  parent_id BIGINT DEFAULT 0,
  name VARCHAR(50) NOT NULL,
  path VARCHAR(80) DEFAULT NULL,
  icon VARCHAR(50) DEFAULT NULL,
  sort INT DEFAULT 0,
