CREATE TABLE aid_rule (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  version VARCHAR(20) NOT NULL COMMENT '规则版本',
  weights VARCHAR(500) NOT NULL COMMENT '因素权重 JSON',
  thresholds VARCHAR(300) NOT NULL COMMENT '等级阈值 JSON',
  status TINYINT DEFAULT 1 COMMENT '1 启用 / 0 历史',
  effect_time DATETIME DEFAULT NULL COMMENT '生效时间',
  creator VARCHAR(50) DEFAULT NULL,
  remark VARCHAR(255) DEFAULT NULL,
  create_time DATETIME DEFAULT NULL,
  UNIQUE KEY uk_version (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='适配度规则配置';


CREATE TABLE aid_score (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  score_no VARCHAR(50) NOT NULL,
  app_id BIGINT NOT NULL,
  app_no VARCHAR(50) DEFAULT NULL,
  rule_version VARCHAR(20) DEFAULT NULL,
  input_snapshot TEXT COMMENT '输入快照 JSON',
  detail_json TEXT COMMENT '各因素得分 JSON',
  total_score DECIMAL(6,2) DEFAULT 0,
  level VARCHAR(10) DEFAULT NULL COMMENT 'A/B/C/D',
  maintain_level VARCHAR(20) DEFAULT NULL COMMENT '维护等级',
  suggest_text VARCHAR(255) DEFAULT NULL,
  advice_json TEXT COMMENT '未满足条件与可改进项',
  manual_score DECIMAL(6,2) DEFAULT NULL,
  manual_level VARCHAR(10) DEFAULT NULL,
  manual_reason VARCHAR(255) DEFAULT NULL,
  manually VARCHAR(50) DEFAULT NULL,
  manual_time DATETIME DEFAULT NULL,
  calc_time DATETIME DEFAULT NULL,
  UNIQUE KEY uk_score_no (score_no),
  KEY idx_app (app_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='适配度计算结果留痕';


CREATE TABLE sys_user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(50) NOT NULL,
  password VARCHAR(100) NOT NULL COMMENT 'BCrypt',
  real_name VARCHAR(50) DEFAULT NULL,
  phone VARCHAR(20) DEFAULT NULL,
  avatar VARCHAR(200) DEFAULT NULL,
  role_code VARCHAR(30) DEFAULT NULL,
  org_name VARCHAR(60) DEFAULT NULL,
  status TINYINT DEFAULT 1,
  last_login DATETIME DEFAULT NULL,
  create_time DATETIME DEFAULT NULL,
  UNIQUE KEY uk_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='系统用户';


CREATE TABLE sys_role (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  role_code VARCHAR(30) NOT NULL,
  role_name VARCHAR(50) NOT NULL,
  data_scope VARCHAR(30) DEFAULT NULL,
  remark VARCHAR(255) DEFAULT NULL,
  create_time DATETIME DEFAULT NULL,
  UNIQUE KEY uk_role_code (role_code)
